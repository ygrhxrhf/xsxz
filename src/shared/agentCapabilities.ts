/**
 * Agent 能力清单：MCP 桥接层与 stdio 服务的单一真源。
 *
 * 本文件只描述"有哪些能力、怎么暴露、有什么副作用"，不执行业务逻辑：
 * 业务实现仍在既有的 `ipcMain.handle` 里，桥接层（P2）按 `channel` 转发。
 *
 * 之所以不让 handler 改成薄转发，见 `docs/agent-integration-design.md` §8：
 * P0 只新增清单；把 handler 体搬进 core 是 P1，而现有 9 个契约测试
 * （`aiRecapIpc.contract.test.ts` 等）按 `ipcMain.handle('<频道>'` 的源码文本
 * 断言 handler 块的内容与顺序，搬走 handler 体会直接破坏它们。
 *
 * 约定：
 * - `tier` 是副作用分级，`confirm` 是执行前的确认方式，两者独立（见设计 §5）。
 * - `deps` 说明运行时依赖，`browse` = 浏览视图 webContents，`view` = 应用内隐藏网络视图，
 *   `key` = safeStorage 解密的凭据，`disk` = 仅磁盘（书库/设置/状态文件）。
 * - `params` 按**代码实际必填性**生成，不按历史契约文档：代码里可选而文档写必填的频道，
 *   这里按可选登记，否则 MCP schema 会给出错误的 required 集合。
 * - `tool === null` 表示不暴露给 agent，替代方案写在 `description` 里。
 * - `job_status` / `job_wait` / `job_cancel` 是桥接层工具，没有对应 IPC 频道，故不在此表。
 */

export type CapabilityTier = 'read' | 'write' | 'destructive'
export type ConfirmationMode = 'none' | 'dry-run' | 'token'
export type CapabilityDependency = 'browse' | 'view' | 'key' | 'disk'

export interface JsonSchemaProperty {
  type: 'string' | 'number' | 'boolean' | 'object' | 'array'
  description: string
  enum?: readonly string[]
  items?: JsonSchemaProperty
  properties?: Record<string, JsonSchemaProperty>
  additionalProperties?: boolean
}

export interface JsonSchema {
  type: 'object'
  description?: string
  properties: Record<string, JsonSchemaProperty>
  required?: readonly string[]
  additionalProperties?: boolean
}

export interface AgentCapability {
  channel: string
  /** MCP 工具名；不暴露的频道为 null。 */
  tool: string | null
  title: string
  description: string
  tier: CapabilityTier
  confirm: ConfirmationMode
  deps: readonly CapabilityDependency[]
  params: JsonSchema
  /** 返回结构摘要，供工具描述与文档生成使用。 */
  result: string
  coreToolset: boolean
}

interface CapabilitySpec extends Omit<AgentCapability, 'tool'> {
  /** 默认 true；显式 false 表示不暴露给 agent。 */
  exposed?: boolean
}

type Field = JsonSchemaProperty & { required?: boolean }

function obj(fields: Record<string, Field> = {}, description?: string): JsonSchema {
  const properties: Record<string, JsonSchemaProperty> = {}
  const required: string[] = []
  for (const [name, field] of Object.entries(fields)) {
    if (field.required) required.push(name)
    properties[name] = {
      type: field.type,
      description: field.description,
      ...(field.enum ? { enum: field.enum } : {}),
      ...(field.items ? { items: field.items } : {}),
      ...(field.properties ? { properties: field.properties } : {}),
      ...(field.additionalProperties ? { additionalProperties: field.additionalProperties } : {}),
    }
  }
  return {
    type: 'object',
    properties,
    ...(required.length ? { required } : {}),
    ...(description ? { description } : {}),
  }
}

/** 形状由 `src/shared/types.ts` 的类型定义承担（标注/站点规则/设置更新等草稿对象）。 */
function openObj(description: string): JsonSchema {
  return { type: 'object', properties: {}, additionalProperties: true, description }
}

const str = (description: string): Field => ({ type: 'string', description, required: true })
const strOpt = (description: string): Field => ({ type: 'string', description })
const num = (description: string): Field => ({ type: 'number', description, required: true })
const numOpt = (description: string): Field => ({ type: 'number', description })
const bool = (description: string): Field => ({ type: 'boolean', description, required: true })
const boolOpt = (description: string): Field => ({ type: 'boolean', description })
const pick = (values: readonly string[], description: string): Field => ({
  type: 'string',
  description,
  enum: values,
  required: true,
})
const pickOpt = (values: readonly string[], description: string): Field => ({
  type: 'string',
  description,
  enum: values,
})
const strings = (description: string): Field => ({
  type: 'array',
  description,
  items: { type: 'string', description: '元素' },
  required: true,
})
const openProp = (description: string): Field => ({
  type: 'object',
  description,
  additionalProperties: true,
  required: true,
})
const openOpt = (description: string): Field => ({
  type: 'object',
  description,
  additionalProperties: true,
})

/** `ns.camelCase` → `ns_snake_case`：MCP 客户端对点号支持不一致，统一取下划线子集。 */
export function toToolName(channel: string): string {
  return channel
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/\./g, '_')
    .toLowerCase()
}

