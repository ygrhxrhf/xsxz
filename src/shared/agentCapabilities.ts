/** 派生工具名：不暴露的频道 `tool` 为 null。 */
export const CAPABILITIES: readonly AgentCapability[] = SPECS.map((spec) => {
  const { exposed, ...rest } = spec
  return { ...rest, tool: exposed === false ? null : toToolName(spec.channel) }
})

export const CAPABILITIES_BY_CHANNEL: ReadonlyMap<string, AgentCapability> = new Map(
  CAPABILITIES.map((capability) => [capability.channel, capability]),
)

/** 暴露给 agent 的能力（`tool !== null`）。 */
export const EXPOSED_CAPABILITIES: readonly AgentCapability[] = CAPABILITIES.filter(
  (capability) => capability.tool !== null,
)

export const EXPOSED_CAPABILITIES_BY_TOOL: ReadonlyMap<string, AgentCapability> = new Map(
  EXPOSED_CAPABILITIES.map((capability) => [capability.tool!, capability]),
)

/** 不暴露的频道，供文档与评审核对"为什么没有对应工具"。 */
export const HIDDEN_CAPABILITIES: readonly AgentCapability[] = CAPABILITIES.filter(
  (capability) => capability.tool === null,
)

export const CORE_CAPABILITIES: readonly AgentCapability[] = EXPOSED_CAPABILITIES.filter(
  (capability) => capability.coreToolset,
)

export type ToolsetName = 'core' | 'all'

/** MCP 服务的 `tools/list` 过滤：core 约 44 个（另加桥接层的 job_status/job_wait/job_cancel）。 */
export function capabilitiesForToolset(toolset: ToolsetName): readonly AgentCapability[] {
  return toolset === 'core' ? CORE_CAPABILITIES : EXPOSED_CAPABILITIES
}

export function capabilityForTool(tool: string): AgentCapability | undefined {
  return EXPOSED_CAPABILITIES_BY_TOOL.get(tool)
}
