import { readFile } from 'node:fs/promises'
import { describe, expect, it } from 'vitest'

describe('Library comfortable card contract', () => {
  it('keeps the fixed grid, generated cover, and keyboard-open structure', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('grid-template-columns: repeat(auto-fill, minmax(230px, 1fr))')
    expect(source).toContain('width: 104px')
    expect(source).toContain('height: 142px')
    expect(source).toContain('width: 6px')
    expect(source).toContain('libraryCoverText(b.title)')
    expect(source).toContain(':style="coverStyle(b.id)"')
    expect(source).toContain('<img v-if="b.coverPath" class="book-cover-img" :src="coverImgSrc(b) || undefined" alt="" />')
    expect(source).toContain('<span v-else>{{ libraryCoverText(b.title) }}</span>')
    expect(source).toContain('libraryCoverSrc')
    expect(source).toContain('class="book-open-area"')
    expect(source).toContain(':aria-label="`打开《${b.title}》`"')
    expect(source).toContain('@click="emit(\'open-book\', b.id)"')
    expect(source).not.toMatch(/<n-card[^>]*@click=/s)
  })

  it('keeps six first-load skeletons and fixed empty-state actions', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('v-if="initialLoading"')
    expect(source).toContain('v-for="index in 6"')
    expect(source).toContain('aria-label="正在加载书库"')
    expect(source).toContain('书库还是空的')
    expect(source).toContain('从网页下载一本书，或导入本地 txt / epub。')
    expect(source).toContain('去浏览找书')
    expect(source).toContain('导入本地书')
    expect(source).toContain('没有找到符合条件的书。')
    expect(source).toContain('清除筛选')
  })

  it('keeps title, author, status, progress, and running result text visible', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('class="book-title" :title="b.title"')
    expect(source).toContain('v-if="b.author" class="book-author" :title="b.author"')
    expect(source).toContain('statusLabel(b.status)')
    expect(source).toContain('class="book-progress" :title="fmtProgress(b)"')
    expect(source).toContain("return '正在检查更新…'")
    expect(source).toContain("return '正在重试失败章…'")
    expect(source).toContain("return '正在导出…'")
    expect(source).toContain('checkMsg.value[book.id] || libraryFailureLabel(book)')
    expect(source).toContain('-webkit-line-clamp: 2')
    expect(source).toContain('text-overflow: ellipsis')
  })

  it('keeps overlapping refreshes visible and rejects stale list responses', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('const refreshTracker = createLibraryRefreshTracker()')
    expect(source).toContain('const requestId = refreshTracker.begin()')
    expect(source).toContain('if (refreshTracker.isLatest(requestId)) {')
    expect(source).toContain('books.value = res.books')
    expect(source).toContain('refreshTracker.end()')
    expect(source).toContain('loading.value = refreshTracker.loading')
  })

  it('routes the fixed more menu without hiding card running state', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    for (const text of ['前情提要', '检查更新', '重试失败章', '查看失败章', '移入回收站']) {
      expect(source).toContain(text)
    }
    expect(source).toContain("const format = entry === 'export-txt' ? 'txt' : 'epub'")
    expect(source).toContain('`导出 ${format}`')
    expect(source).toContain(':options="cardMenuOptions(b)"')
    expect(source).toContain(':aria-label="`更多操作：《${b.title}》`"')
    expect(source).toContain("if (action === 'recap') void openRecap(book)")
    expect(source).toContain("else if (action === 'check-update') void handleCheckUpdate(book.id)")
    expect(source).toContain("else if (action === 'retry-failed') void handleRetry(book.id)")
    expect(source).toContain("else if (action === 'view-failed') void openFailedList(book.id, book.title)")
    expect(source).toContain("else if (action === 'export-txt') void handleExport(book.id, 'txt')")
    expect(source).toContain("else if (action === 'export-epub') void handleExport(book.id, 'epub')")
    expect(source).toContain("else if (action === 'trash') deleteConfirmId.value = book.id")
    expect(source).toContain('disabled: running')
    expect(source).toContain('preset="dialog"')
    expect(source).toContain('把《{{ deleteConfirmBook?.title }}》移入回收站？之后可在回收站还原。')
    expect(source).toContain('@positive-click="deleteConfirmId && confirmDelete(deleteConfirmId)"')
    expect(source).toContain(':loading="hasTask(retryingIds, failedBookId)"')
    expect(source).toContain(':disabled="hasTask(activeDownloadIds, failedBookId)"')
    expect(source).not.toMatch(/retryingId(?!s)/)
    expect(source).not.toContain('<n-popconfirm\n          :show="deleteConfirmId === b.id"')
    expect(source).not.toContain('legacy-card-actions')
  })

  it('matches search q against title, author, and tags, and focuses find with Ctrl/Meta+F', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('placeholder="按书名、作者或标签筛选"')
    expect(source).toContain('ref="searchInputRef"')
    expect(source).toContain('window.addEventListener(\'keydown\', onLibraryKeydown)')
    expect(source).toContain('window.removeEventListener(\'keydown\', onLibraryKeydown)')
    expect(source).toContain('if (!props.active) return')
    expect(source).toContain('if (!isLibraryFindShortcut(e)) return')
    expect(source).toContain('e.preventDefault()')
    expect(source).toContain('searchInputRef.value?.focus()')
  })

  it('renders single-select tag chips from all books and combines with search/status', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('collectLibraryTags')
    expect(source).toContain('v-if="libraryTags.length"')
    expect(source).toContain('class="lib-tag-chips"')
    expect(source).toContain('aria-label="按标签筛选"')
    expect(source).toContain('v-for="tag in libraryTags"')
    expect(source).toContain('@update:checked="toggleLibraryTag(tag)"')
    expect(source).toContain('selectedTag: selectedTag.value')
    expect(source).toContain("selectedTag.value = isSelectedLibraryTag(tag) ? '' : tag")
    expect(source).toContain('selectedTag.value = \'\'')
    expect(source).not.toContain('v-html')
  })

  it('opens a Chinese 编辑信息 dialog, validates title, and saves via updateMeta', async () => {
    const source = await readFile(new URL('./Library.vue', import.meta.url), 'utf-8')
    expect(source).toContain('@click="openEdit(b)">编辑信息</n-button>')
    expect(source).toContain('title="编辑信息"')
    expect(source).toContain('<n-form-item label="书名">')
    expect(source).toContain('<n-form-item label="作者">')
    expect(source).toContain('<n-form-item label="标签">')
    expect(source).toContain('<n-dynamic-tags')
    expect(source).toContain('@update:value="onEditTagsUpdate"')
    expect(source).toContain('onTagInputKeydown')
    expect(source).toContain('normalizeEditTags')
    expect(source).toContain('@click="closeEdit">取消</n-button>')
    expect(source).toContain('@click="saveEdit">保存</n-button>')
    expect(source).toContain("message.error('书名不能为空')")
    expect(source).toContain('window.api.library.updateMeta')
    expect(source).toContain("message.success('已保存')")
    expect(source).toContain('await refresh()')
    expect(source).toContain("message.error('保存失败，已保留原来的信息')")
    expect(source).toContain('@click="pickCover">选择封面</n-button>')
    expect(source).toContain('window.api.library.pickCoverFile')
    expect(source).toContain('window.api.library.setCover')
    expect(source).toContain('if (sourcePath == null) return')
    expect(source).toContain('mapLibraryCoverError')
    expect(source).toContain("message.success('已保存')")
    expect(source).not.toContain('<n-button disabled>选择封面</n-button>')
    expect(source).not.toContain('v-html')
    const pickBlock = source.slice(source.indexOf('async function pickCover()'), source.indexOf('async function saveEdit()'))
    expect(pickBlock).toContain('window.api.library.pickCoverFile')
    expect(pickBlock).toContain('if (sourcePath == null) return')
    expect(pickBlock).toContain('window.api.library.setCover')
    expect(pickBlock).toContain("message.success('已保存')")
    expect(pickBlock).toContain('await refresh()')
    expect(pickBlock).toContain('mapLibraryCoverError')
    const cancelGuard = pickBlock.slice(
      pickBlock.indexOf('if (sourcePath == null)'),
      pickBlock.indexOf('editCoverSaving.value = true'),
    )
    expect(cancelGuard).toContain('return')
    expect(cancelGuard).not.toContain('message.')
    expect(cancelGuard).not.toContain('setCover')
    const saveBlock = source.slice(source.indexOf('async function saveEdit()'), source.indexOf('function statusLabel'))
    expect(saveBlock).toContain('window.api.library.updateMeta')
    const titleGuard = saveBlock.slice(saveBlock.indexOf('if (!title)'), saveBlock.indexOf('editSaving.value = true'))
    expect(titleGuard).toContain("message.error('书名不能为空')")
    expect(titleGuard).toContain('return')
    expect(titleGuard).not.toContain('updateMeta')
    const closeBlock = source.slice(source.indexOf('function closeEdit()'), source.indexOf('function onEditShow'))
    expect(closeBlock).not.toContain('updateMeta')
    expect(closeBlock).toContain('editOpen.value = false')
  })
})
